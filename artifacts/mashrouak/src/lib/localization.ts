export function translateText(language: string, text: string): string {
  if (language !== 'en') return text;
  const trimmed = text.trim();
  const translated = englishTranslations[trimmed];
  if (translated) return text.replace(trimmed, translated);
  const dynamicTemplates: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [/^(\d+) منتجات متاحة$/, ([, count]) => `${count} products available`],
    [/^تم إنشاء (\d+) طلب مستقل\. الدفع نقداً عند الاستلام\.$/, ([, count]) => `${count} separate orders created. Cash on delivery.`],
    [/^الخطوة (\d+) من 3 · (\d+) طلب مستقل من مشاريع مختلفة$/, ([, step, count]) => `Step ${step} of 3 · ${count} separate orders from different projects`],
    [/^إنشاء حساب (.+)$/, ([, role]) => `Create a ${translateText(language, role)} account`],
    [/^بيانات تجريبية فقط: (.+) · كلمة المرور: demo123$/, ([, email]) => `Demo credentials only: ${email} · password: demo123`],
    [/^السلة، (\d+) منتجات$/, ([, count]) => `Cart, ${count} items`],
  ];
  const template = dynamicTemplates.find(([pattern]) => pattern.test(trimmed));
  if (template) return text.replace(trimmed, template[1](trimmed.match(template[0])!));
  const dynamicPrefix: Array<[string, string]> = [
    ['صباح الخير، ', 'Good morning, '],
    ['استلام من: ', 'Pickup from: '],
    ['التوصيل إلى: ', 'Deliver to: '],
    ['المسافة إلى الاستلام: ', 'Distance to pickup: '],
    ['تم إلغاء الطلب من ', 'Order cancelled by '],
    ['تسجيل الدخول كـ ', 'Sign in as '],
    ['السلة، ', 'Cart, '],
    ['منتجات ', 'Products '],
    ['تعديل ', 'Edit '],
    ['حذف ', 'Delete '],
    ['طلب ', 'Order '],
    ['توصيل ', 'Delivery '],
    ['استلام ', 'Pickup '],
    ['زيارة ', 'Visit '],
    ['إضافة ', 'Add '],
  ];
  const prefix = dynamicPrefix.find(([arabic]) => trimmed.startsWith(arabic));
  const translatedText = prefix
    ? text.replace(
      trimmed,
      `${prefix[1]}${translateText(language, trimmed.slice(prefix[0].length))}`,
    )
    : text;
  return translatedText
    .replaceAll('د.أ', 'JOD')
    .replace(/[٠-٩]/g, (digit) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(digit)));
}

function translateValue(language: string, value: unknown): unknown {
  if (typeof value === 'string') return translateText(language, value);
  if (Array.isArray(value)) return value.map((item) => translateValue(language, item));
  if (isValidElement(value)) {
    const element = value as ReactElement<Record<string, unknown>>;
    const props = Object.fromEntries(
      Object.entries(element.props).map(([key, propValue]) => [
        key,
        translateValue(language, propValue),
      ]),
    );
    return cloneElement(element, props);
  }
  if (value && typeof value === 'object' && Object.getPrototypeOf(value) === Object.prototype) {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, translateValue(language, item)]),
    );
  }
  return value;
}

export function LocalizedContent({
  language,
  children,
}: {
  language: string;
  children: ReactNode;
}) {
  return translateValue(language, children) as ReactNode;
}
